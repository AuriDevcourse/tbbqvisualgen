// `npm run logos:tiers:gen` — turn partner-tiers-report.json into the
// ALL_PARTNER_TIERS block in src/data/partnerSets.ts.
//
// Run `npm run logos:tiers -- --write` first: that resolves every row in the
// Airtable view to a library file (and imports the ones we don't hold). This
// script only writes the roster into source, between the two markers below, so
// a re-sync is a two-command job instead of 200 hand edits.
//
// Everything OUTSIDE the markers is hand-written and never touched.
import { readFileSync, writeFileSync } from "node:fs";

const START = "// ── ALL_PARTNER_TIERS · generated by npm run logos:tiers:gen ─────────────";
const END = "// ── end generated block ─────────────────────────────────────────────────";
const FILE = "src/data/partnerSets.ts";

const report = JSON.parse(readFileSync("partner-tiers-report.json", "utf8"));
if (!report.write) {
  console.error("partner-tiers-report.json is from a DRY RUN — run `npm run logos:tiers -- --write` first,");
  console.error("else the roster can point at files that were never imported.");
  process.exit(1);
}

const LADDER = ["Prime", "Main", "Conqueror", "Pioneer", "Core", "Challenger", "Community"];
const id = (tier) => tier.toLowerCase().replace(/[^a-z0-9]+/g, "-");
const q = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

const tiers = report.tiers.filter((t) => t.logos.length);
const lines = [];
lines.push(START);
lines.push(`/** Every partner on the website list, grouped by tier and ordered by tier`);
lines.push(` *  value, high to low. ${report.tiers.reduce((n, t) => n + t.logos.length, 0)} partners across ${tiers.length} tiers, generated from`);
lines.push(` *  Airtable on the date in the git history of this block — re-run the two`);
lines.push(` *  logos:tiers commands to refresh it, never hand-edit inside the markers. */`);
lines.push(`export const ALL_PARTNER_TIERS: PartnerTierRoster[] = [`);
for (const t of tiers) {
  lines.push(`  {`);
  lines.push(`    id: ${q(id(t.tier))},`);
  lines.push(`    tier: ${q(t.tier)},`);
  // The seven money tiers are one ladder: a higher tier must never draw smaller
  // than a lower one on the tiered wall. The groups after them are separate
  // deals and size themselves freely.
  lines.push(`    ladder: ${LADDER.includes(t.tier)},`);
  lines.push(`    logos: [`);
  for (const l of t.logos) lines.push(`      { label: ${q(l.company)}, src: ${q(l.src)} },`);
  lines.push(`    ],`);
  lines.push(`  },`);
}
lines.push(`];`);
lines.push("");
lines.push(`/** The partners this roster could NOT place, kept in source so the gap is`);
lines.push(` *  visible rather than silently missing from a wall. Each needs artwork a`);
lines.push(` *  script cannot produce — see the reasons in partner-tiers-report.json. */`);
lines.push(`export const ALL_PARTNERS_UNRESOLVED: { label: string; tier: string; why: string }[] = [`);
for (const p of report.problems) {
  lines.push(`  { label: ${q(p.company)}, tier: ${q(p.tier)}, why: ${q(p.why.replace(/\\/g, "/"))} },`);
}
lines.push(`];`);
lines.push(END);

const src = readFileSync(FILE, "utf8");
const from = src.indexOf(START);
const to = src.indexOf(END);
if (from < 0 || to < 0) {
  console.error(`markers not found in ${FILE} — add both marker lines where the block should live:`);
  console.error(START);
  console.error(END);
  process.exit(1);
}
const next = src.slice(0, from) + lines.join("\n") + src.slice(to + END.length);
writeFileSync(FILE, next);
console.log(`${FILE}: ${tiers.length} tiers, ${tiers.reduce((n, t) => n + t.logos.length, 0)} partners, ${report.problems.length} unresolved`);
for (const t of tiers) console.log(`  ${t.tier.padEnd(16)}${String(t.logos.length).padStart(4)}`);
