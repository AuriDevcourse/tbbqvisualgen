// `npm run logos:match`
//
// Join the partner list (name + real website) to the logo library, producing the
// "logo file|domain" batch that logos:verify / logos:compare consume.
//
// This exists because guessing domains from a company name FAILED: across 782
// logos it produced 217 non-resolving and 56 parked domains, almost all bad
// guesses. Real URLs come from the partner list instead — and that list is also
// the right subset to check, since those are the partners actually published.
import { readFileSync, writeFileSync } from "node:fs";

const LOGOS = JSON.parse(readFileSync("src/data/logoLibrary.json", "utf8"));
const PARTNERS = readFileSync(process.argv[2] ?? "scripts/logo-checks/techbbq-partners.txt", "utf8")
  .split("\n").map((l) => l.trim())
  .filter((l) => l && !l.startsWith("#"))
  .map((l) => {
    const [name, url] = l.split("|").map((s) => s.trim());
    return { name, url, host: (() => { try { return new URL(url).host.replace(/^www\./, ""); } catch { return ""; } })() };
  })
  .filter((p) => p.host);

const TR = { ø: "o", æ: "ae", œ: "oe", å: "a", ð: "d", đ: "d", ł: "l", ß: "ss", þ: "th" };
const fold = (s) => s.toLowerCase().replace(/[øæœåðđłßþ]/g, (c) => TR[c] ?? c)
  .normalize("NFD").replace(/\p{Diacritic}/gu, "").replace(/[^a-z0-9]/g, "");
// Variant words are not part of the company's identity when matching.
const STRIP = /\b(white|black|dark|light|colour|color|grey|mono|inverted|negative|horizontal|vertical|stacked|full|icon|mark|large|small|2)\b/gi;
const key = (s) => fold(s.replace(STRIP, " "));
/** Folded words, so a partner name can be matched at word boundaries. */
const words = (s) => s.replace(STRIP, " ").split(/[^a-zA-Z0-9]+/).map(fold).filter(Boolean);

const matched = [];
const unmatchedPartners = [];
for (const p of PARTNERS) {
  const pk = key(p.name);
  const pw = words(p.name);
  // Exact key first; then a WORD-BOUNDARY prefix ("CSE" -> "CSE Advisory"), which
  // is safe for short acronyms; then loose containment, floored at 5 chars so a
  // short acronym cannot swallow an unrelated name. The floor matters: a bare
  // "Innovation" logo used to claim HSBC Innovation Banking.
  const hits = LOGOS.filter((l) => key(l.name) === pk)
    .concat(LOGOS.filter((l) => {
      const lw = words(l.name);
      return key(l.name) !== pk && pw.length > 0 && lw.length > pw.length
        && pw.every((w, i) => lw[i] === w);
    }))
    .concat(LOGOS.filter((l) => {
      const lk = key(l.name);
      return lk !== pk && lk.length >= 5 && pk.length >= 5 && (lk.includes(pk) || pk.includes(lk));
    }));
  const uniq = [...new Map(hits.map((h) => [h.src, h])).values()];
  if (!uniq.length) { unmatchedPartners.push(p); continue; }
  for (const l of uniq) {
    matched.push({ file: decodeURIComponent(l.src.replace("/logos/", "")), partner: p.name, host: p.host });
  }
}

const matchedFiles = new Set(matched.map((m) => m.file));
writeFileSync("scripts/logo-checks/partner-batch.txt",
  `# Generated by npm run logos:match — "logo file|domain" for logos_verify/compare.\n` +
  matched.map((m) => `${m.file}|${m.host}`).join("\n") + "\n");

console.log(`partners in list:        ${PARTNERS.length}`);
console.log(`logo files matched:      ${matchedFiles.size}  (${matched.length} name pairings incl. variants)`);
console.log(`partners with NO logo:   ${unmatchedPartners.length}`);
console.log(`\n— partners we have no logo for (worth chasing) —`);
for (const p of unmatchedPartners) console.log(`  ${p.name.padEnd(34)} ${p.host}`);
console.log(`\nbatch written: scripts/logo-checks/partner-batch.txt`);
